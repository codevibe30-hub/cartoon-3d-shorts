"""Build src/videos/tikus/captions.ts: two-word caption groups with
frame timings from voice/words.json (faster-whisper ASR), but with
the TEXT taken from the actual script (voice/lines.txt) — whisper's
Indonesian spelling is unreliable ("kuhil", "beren karnasi"), so
ASR words are aligned to script words per line via difflib and the
script's words inherit the ASR timings. Emits { from, to, text }."""
import difflib, json, math, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
words = json.load(open(os.path.join(ROOT, "voice", "words.json")))
starts = json.load(open(os.path.join(ROOT, "voice", "line_starts.json")))
lines = [ln.strip() for ln in open(os.path.join(ROOT, "voice", "lines.txt")) if ln.strip()]

def norm(tok):
    return re.sub(r"[^a-z0-9]", "", tok.lower())

# ASR words bucketed per script line by the line start times
buckets = [[] for _ in lines]
for w in words:
    li = 0
    for i, s in enumerate(starts["starts"]):
        if w["s"] >= s - 0.25:
            li = i
    buckets[li].append(w)

timed = []  # (text, start_s, end_s) with SCRIPT text + ASR timing
for li, line in enumerate(lines):
    script = line.split()
    asr = buckets[li]
    if not asr:
        continue
    sm = difflib.SequenceMatcher(a=[norm(w["w"]) for w in asr],
                                 b=[norm(t) for t in script], autojunk=False)
    pairs = []  # (script_idx, s, e)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "delete":
            continue  # extra ASR noise: its time is absorbed by neighbours
        if tag == "insert":
            # script words the ASR missed: split the gap between the
            # neighbouring timed words evenly
            t_prev = pairs[-1][2] if pairs else asr[0]["s"]
            t_next = asr[i1]["s"] if i1 < len(asr) else asr[-1]["e"]
            span = max(t_next - t_prev, 0.05 * (j2 - j1))
            for k in range(j1, j2):
                s0 = t_prev + span * (k - j1) / (j2 - j1)
                pairs.append((k, s0, s0 + span / (j2 - j1)))
            continue
        # equal / replace: pair up in order; surplus script words
        # subdivide the block, surplus ASR words merge their span
        na, nb = i2 - i1, j2 - j1
        t0 = asr[i1]["s"]; t1 = asr[i2 - 1]["e"]
        for k in range(nb):
            ai = i1 + min(int(k * na / nb), na - 1)
            s0 = asr[ai]["s"] if k * na % nb == 0 or na >= nb else t0 + (t1 - t0) * k / nb
            e0 = asr[ai]["e"] if na >= nb else t0 + (t1 - t0) * (k + 1) / nb
            pairs.append((j1 + k, s0, max(e0, s0 + 0.05)))
    pairs.sort(key=lambda p: p[0])
    for j, s0, e0 in pairs:
        timed.append((script[j], s0, e0))

groups = []
for i in range(0, len(timed), 2):
    pair = timed[i:i + 2]
    groups.append({
        "from": math.floor(pair[0][1] * 30),
        "to": math.ceil(pair[-1][2] * 30),
        "text": " ".join(p[0] for p in pair),
    })
out = os.path.join(ROOT, "src", "videos", "tikus", "captions.ts")
with open(out, "w") as fh:
    fh.write("// GENERATED by scripts/gen_captions.py: script text timed by voice/words.json.\n")
    fh.write("// Subtitle rule: ONE bottom line, TWO WORDS per display, karaoke word-sync.\n")
    fh.write("// Nunito weight 500, 99px.\n")
    fh.write("export type Cap = { from: number; to: number; text: string };\n")
    fh.write("export const CAPTIONS: Cap[] = [\n")
    for g in groups:
        fh.write(" " + json.dumps(g, ensure_ascii=False) + ",\n")
    fh.write("];\n")
print(f"{len(timed)} words, {len(groups)} caption groups -> {out}")
print(" | ".join(g["text"] for g in groups[:10]))
