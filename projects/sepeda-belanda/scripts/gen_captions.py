"""Generate src/videos/example/captions.ts — subtitle rule: ONE line at the bottom,
TWO WORDS per display, karaoke-style following the narrator word by word. Each pair
appears exactly when its first word is spoken (timings from voice/words.json, script
words mapped onto whisper tokens inside each line's window). Font: Nunito weight 500,
99px — two words always fit the 1000px line limit with room to spare;
scripts/measure_widths.mjs verify still checks every chunk as an exact string.
Set EPISODE=<folder> to target another episode folder under src/videos/."""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
EPISODE = os.environ.get("EPISODE", "example")
FPS = 30
lines = [l.strip() for l in open(os.path.join(ROOT, "voice/lines.txt")) if l.strip()]
starts = json.load(open(os.path.join(ROOT, "voice/line_starts.json")))
words = json.load(open(os.path.join(ROOT, "voice/words.json")))
TOTAL_S = starts["total"]

caps = []
for i, line in enumerate(lines):
    ls = starts["starts"][i]
    le = starts["starts"][i + 1] if i + 1 < len(starts["starts"]) else TOTAL_S
    ww = [w for w in words if ls - 0.3 <= w["s"] < le + 0.05]
    toks = line.split()
    if not ww:
        continue
    # frame span per script word, from the whisper token at the same index
    spans = []
    for j, tok in enumerate(toks):
        w = ww[min(j, len(ww) - 1)]
        spans.append((round(w["s"] * FPS), round(w["e"] * FPS)))
    # pair the words: (0,1), (2,3), ... a trailing odd word displays alone
    for j in range(0, len(toks), 2):
        pair = toks[j:j + 2]
        frm = spans[j][0]
        if j + 2 < len(toks):
            to = spans[j + 2][0]
        else:
            to = spans[-1][1] + 2
        caps.append({"from": frm, "to": to, "text": " ".join(pair)})
# enforce monotonic, non-overlapping, within film
for i in range(1, len(caps)):
    if caps[i]["from"] < caps[i - 1]["to"]:
        caps[i]["from"] = caps[i - 1]["to"]
    if caps[i]["to"] <= caps[i]["from"]:
        caps[i]["to"] = caps[i]["from"] + 6
caps[0]["from"] = min(caps[0]["from"], 1)
caps[-1]["to"] = min(caps[-1]["to"], round(TOTAL_S * FPS) - 1)

out = ["// GENERATED by scripts/gen_captions.py from voice/words.json + line_starts.json.",
       "// Subtitle rule: ONE bottom line, TWO WORDS per display, karaoke word-sync.",
       "// Nunito weight 500, 99px.",
       "export type Cap = { from: number; to: number; text: string };",
       "export const CAPTIONS: Cap[] = ["]
for c in caps:
    out.append(f' {{ "from": {c["from"]}, "to": {c["to"]}, "text": {json.dumps(c["text"], ensure_ascii=False)} }},')
out.append("];")
open(os.path.join(ROOT, "src/videos", EPISODE, "captions.ts"), "w").write("\n".join(out) + "\n")
print(f"{len(caps)} two-word chunks")
for c in caps[:10]: print(c["from"], c["to"], c["text"])
